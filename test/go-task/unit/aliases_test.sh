#!/usr/bin/env bash
# Docker-free test of the go-task Feature's team task aliases (docs/proposals/task-aliases.md, slice 1):
# the generator src/go-task/task-aliases and the registry's include of its output
# (src/go-task/task-features-registry). Uses the real `task` and a real yq (the one on PATH, else the
# pinned release downloaded through dcf_curl and sha256-verified). Everything runs in a temp folder
# through GO_TASK_SHARE / GO_TASK_STATE; nothing on the machine is touched. Part of `task lint`
# (`task test:go-task-unit`). TASK_ALIASES_SH / TASK_FEATURES_REGISTRY point the test at other copies
# (the mutation check).
set -u
exec </dev/null

here="$(cd "$(dirname "$0")" && pwd)"
src="$here/../../../src/go-task"
gen="${TASK_ALIASES_SH:-$src/task-aliases}"
registry="${TASK_FEATURES_REGISTRY:-$src/task-features-registry}"

T="$(mktemp -d)"
trap 'rm -rf "$T"' EXIT
pass=0 fail=0
check() { # <name> <expected> <actual>
  if [ "$2" = "$3" ]; then pass=$((pass + 1)); echo "ok   - $1"
  else fail=$((fail + 1)); echo "FAIL - $1"; echo "  expected: $2"; echo "  actual:   $3"; fi
}
contains() { # <name> <needle> <haystack>
  case "$3" in *"$2"*) pass=$((pass + 1)); echo "ok   - $1" ;;
    *) fail=$((fail + 1)); echo "FAIL - $1 (no '$2' in:)"; printf '    %s\n' "$3" ;; esac
}
lacks() { # <name> <needle> <haystack>
  case "$3" in *"$2"*) fail=$((fail + 1)); echo "FAIL - $1 (found '$2' in:)"; printf '    %s\n' "$3" ;;
    *) pass=$((pass + 1)); echo "ok   - $1" ;; esac
}

command -v task >/dev/null 2>&1 || { echo "FAIL - task is not on PATH"; exit 1; }

# --- yq: PATH, else the pinned release
yq_version=4.54.1
yq_sha_amd64=8e34fc298390875de416e6a4afcb8cabeceb25d9aa8506c1a2f9353cf702ea5f
yq="${TASK_ALIASES_YQ:-$(command -v yq || true)}"
if [ -z "$yq" ] || ! "$yq" --version 2>&1 | grep -q mikefarah; then
  # shellcheck source=src/go-task/dcf-curl.sh
  . "$src/dcf-curl.sh"
  yq="$T/yq"
  if [ "$(uname -m)" = x86_64 ] && dcf_curl -fsSL -o "$yq" "https://github.com/mikefarah/yq/releases/download/v$yq_version/yq_linux_amd64" \
    && echo "$yq_sha_amd64  $yq" | sha256sum -c - >/dev/null 2>&1; then
    chmod +x "$yq"
  else
    echo "FAIL - no mikefarah yq on PATH and the pinned one could not be fetched"; exit 1
  fi
fi
export TASK_ALIASES_YQ="$yq"

# --- a workspace: a root Taskfile that includes features.yml (flattened) as the Feature documents,
# with a real task that has an alias, and an include with an alias (dcx for dc)
W="$T/ws"
export GO_TASK_SHARE="$T/share" GO_TASK_STATE="$T/state"
mkdir -p "$W/.devcontainer" "$W/sub" "$GO_TASK_SHARE/includes.d" "$GO_TASK_STATE" "$T/bin"
ln -s "$gen" "$T/bin/task-aliases"
export PATH="$T/bin:$PATH"
cat > "$W/Taskfile.yml" <<E
version: '3'
includes:
  features:
    taskfile: $GO_TASK_SHARE/features.yml
    optional: true
    flatten: true
  dc:
    taskfile: ./dc.yml
    aliases: [dcx]
tasks:
  real:
    aliases: [rl]
    desc: a real task
    cmds:
      - echo "real P={{.P | default "none"}} N={{.N | default "none"}}"
E
cat > "$W/dc.yml" <<'E'
version: '3'
tasks:
  up:
    desc: up
    cmds: [echo up]
E
cp "$src/taskfile.yml" "$GO_TASK_SHARE/includes.d/go-task.yml"
touch "$GO_TASK_SHARE/aliases.enabled"
bash "$registry" >/dev/null
out="$GO_TASK_STATE/aliases.yml"
team="$W/.devcontainer/task-aliases.yml"
regen() { (cd "${1:-$W}" && task-aliases generate 2>&1); }
listing() { (cd "$W" && task --list 2>&1); }

# ---------------------------------------------------------------- 7. the registry
R="$T/reg"
mkdir -p "$R/share/includes.d"
touch "$R/share/includes.d/a.yml" "$R/share/includes.d/b.yml"
GO_TASK_SHARE="$R/share" GO_TASK_STATE="$R/state" bash "$registry" >/dev/null
check "registry, taskAliases off: features.yml is what it always was" \
"# Generated by task-features-registry (go-task Feature). Do not edit:
# it is rebuilt from $R/share/includes.d/*.yml whenever a Feature installs.
version: '3'
includes:
  a:
    taskfile: $R/share/includes.d/a.yml
  b:
    taskfile: $R/share/includes.d/b.yml" "$(cat "$R/share/features.yml")"
rm "$R/share/includes.d/"*.yml
GO_TASK_SHARE="$R/share" GO_TASK_STATE="$R/state" bash "$registry" >/dev/null
check "registry, off and nothing registered: includes: {}" "includes: {}" "$(grep '^includes' "$R/share/features.yml")"
touch "$R/share/includes.d/a.yml" "$R/share/aliases.enabled"
GO_TASK_SHARE="$R/share" GO_TASK_STATE="$R/state" bash "$registry" >/dev/null
check "registry, taskAliases on: the generated file is included once, optional, flattened" \
"includes:
  a:
    taskfile: $R/share/includes.d/a.yml
  task-aliases:
    taskfile: $R/state/aliases.yml
    optional: true
    flatten: true" "$(sed -n '/^includes/,$p' "$R/share/features.yml")"
rm "$R/share/includes.d/a.yml"
GO_TASK_SHARE="$R/share" GO_TASK_STATE="$R/state" bash "$registry" >/dev/null
contains "registry, on and nothing else registered: only the alias include" "  task-aliases:" "$(cat "$R/share/features.yml")"
lacks "registry, on and nothing else registered: no literal glob" "*.yml" "$(sed -n '/^includes/,$p' "$R/share/features.yml")"

# ---------------------------------------------------------------- 1. the format, 2. generation
cat > "$team" <<'E'
# the team file
aliases:
  briefing: devhost-real        # short form
  b:
    task: real
  cost-report:
    task: real
    desc: "the month's spend: a #test"
  ts:
    task: real
    vars: { P: "me's: #x # y", N: 3 }
  bar:tab:
    task: real
    vars: { P: true }
E
sed -i 's/devhost-real/real/' "$team"
report="$(regen)"
check "an accepted alias is ok in the report (short form)" "ok" "$(echo "$report" | awk '$1 == "briefing" { print $3 }')"
check "five aliases ok, none refused" "aliases: 5 ok, 0 not generated" "$(echo "$report" | sed -n 's/^\(aliases: [0-9]* ok, [0-9]* not generated\).*/\1/p')"
check "golden output: wrappers with quoting for ' : and #" "# Generated by task-aliases (go-task Feature). Do not edit: regenerate with
# \`task go-task:aliases\`. Source: the team aliases file.
version: '3'
tasks:
  'briefing':
    desc: 'alias for real'
    dir: '{{.USER_WORKING_DIR}}'
    cmds:
      - task: 'real'
  'b':
    desc: 'alias for real'
    dir: '{{.USER_WORKING_DIR}}'
    cmds:
      - task: 'real'
  'cost-report':
    desc: 'the month''s spend: a #test'
    dir: '{{.USER_WORKING_DIR}}'
    cmds:
      - task: 'real'
  'ts':
    desc: 'alias for real'
    dir: '{{.USER_WORKING_DIR}}'
    cmds:
      - task: 'real'
        vars: { P: 'me''s: #x # y', N: '3' }
  'bar:tab':
    desc: 'alias for real'
    dir: '{{.USER_WORKING_DIR}}'
    cmds:
      - task: 'real'
        vars: { P: 'true' }" "$(cat "$out")"
l="$(listing)"
contains "the aliases show in task --list, flattened (no features: prefix)" "* briefing:" "$l"
contains "a colon name shows in task --list" "* bar:tab:" "$l"
contains "the desc default and a custom desc" "the month's spend: a #test" "$l"
check "task <alias> calls the target with its fixed vars (quotes survive)" "real P=me's: #x # y N=3" "$(cd "$W" && task ts --silent 2>&1)"
check "a task call without vars leaves the target's own default" "real P=none N=none" "$(cd "$W" && task b --silent 2>&1)"
check "works from a sub folder (the team file is found through the root Taskfile)" "ok" "$(regen "$W/sub" | awk '$1 == "ts" { print $3 }')"
a="$(cat "$out")"; regen >/dev/null
check "regenerating is idempotent" "$a" "$(cat "$out")"
check "the alias task of the Feature runs the generator" "ok" "$(cd "$W/sub" && task go-task:aliases 2>&1 | awk '$1 == "ts" { print $3 }')"
echo "aliases: { extra: real }" > "$team"
regen >/dev/null
check "regenerated after the file changes, no rebuild: the old alias is gone" "" "$(grep -c "'ts'" "$out" | grep -v '^0$')"
contains "regenerated after the file changes: the new one is there" "'extra'" "$(cat "$out")"

# the rejected cases of section 3
bad() { # <name> <yaml of one alias> <status> <note fragment>
  printf 'aliases:\n%s\n' "$2" > "$team"
  r="$(regen)"
  check "$1: status" "$3" "$(echo "$r" | awk 'NR == 2 { print $3 }')"
  contains "$1: note" "$4" "$(echo "$r" | sed -n 2p)"
  check "$1: no wrapper written" "tasks: {}" "$(grep '^tasks' "$out")"
}
bad "a bad name (upper case)" "  Bad: real" invalid "name must match"
bad "a bad name (space-free punctuation)" "  'a!': real" invalid "name must match"
bad "a name with a leading colon" "  ':a': real" invalid "name must match"
bad "a target with a bad character" "  a: 'real; rm -rf /'" invalid "not a task name"
bad "a missing task key" "  a: { desc: hello }" invalid "task is required"
bad "cmds is not accepted" "  a: { task: real, cmds: [echo hi] }" invalid "unknown key 'cmds'"
bad "deps is not accepted" "  a: { task: real, deps: [real] }" invalid "unknown key 'deps'"
bad "env is not accepted" "  a: { task: real, env: { A: b } }" invalid "unknown key 'env'"
bad "dir is not accepted" "  a: { task: real, dir: / }" invalid "unknown key 'dir'"
bad "preconditions is not accepted" "  a: { task: real, preconditions: [x] }" invalid "unknown key 'preconditions'"
bad "a templated var" "  a: { task: real, vars: { P: '{{.X}}' } }" invalid "{{"
bad "a shell var" "  a: { task: real, vars: { P: { sh: 'echo hi' } } }" invalid "sh:, ref:"
bad "a ref var" "  a: { task: real, vars: { P: { ref: .X } } }" invalid "sh:, ref:"
bad "a list var" "  a: { task: real, vars: { P: [a, b] } }" invalid "plain string, number or boolean"
bad "a bad var name" "  a: { task: real, vars: { 'P Q': x } }" invalid "not an identifier"
bad "vars that is not a map" "  a: { task: real, vars: x }" invalid "vars must be a map"
bad "a multi-line desc" $'  a:\n    task: real\n    desc: |\n      one\n      two' invalid "one line"
bad "a templated desc" "  a: { task: real, desc: '{{.X}}' }" invalid "one line"
bad "a number instead of a task name" "  a: 5" invalid "must be a task name"
bad "a list" "  a: [real]" invalid "must be a task name"
sed -i '2,$d' "$team"

# ---------------------------------------------------------------- 3. conflicts
cat > "$team" <<'E'
aliases:
  real: go-task:version
  rl: go-task:version
  dcx:up: go-task:version
  dc:up: go-task:version
  go-task:version: real
  gone: no-such-task
  a: real
  b: a
  ok1: real
E
r="$(regen)"
st() { echo "$r" | awk -v n="$1" '$1 == n { print $3 }'; }
check "an alias named like a real task is refused (shadows)" "shadows" "$(st real)"
check "an alias named like a Task alias of a real task is refused" "shadows" "$(st rl)"
check "an alias named like an include alias (dcx:up for dc:up) is refused" "shadows" "$(st dcx:up)"
check "an alias named like an included task (dc:up) is refused" "shadows" "$(st dc:up)"
check "an alias named like a Feature task is refused" "shadows" "$(st go-task:version)"
check "a missing target is broken, no wrapper" "broken" "$(st gone)"
check "an alias to an alias is refused" "invalid" "$(st b)"
check "the valid alias next to the refused ones is still generated" "ok" "$(st ok1)"
check "the report counts them" "aliases: 2 ok, 7 not generated" "$(echo "$r" | sed -n 's/^\(aliases: [0-9]* ok, [0-9]* not generated\).*/\1/p')"
lacks "no wrapper for a shadowing alias" "'real'" "$(grep "^  '" "$out")"
check "the Feature's own tasks still run after generation" "real P=none N=none" "$(cd "$W" && task a --silent 2>&1)"
check "task --list still works with the refused aliases" "0" "$(cd "$W" && task --list >/dev/null 2>&1; echo $?)"

# Task's own behaviour, the premise of refusing a shadowing wrapper: a second task of the same name
# fails the whole run (Task 3.54: "Found multiple tasks"), so the generator must never emit one.
cp "$out" "$T/good.yml"
printf "version: '3'\ntasks:\n  real:\n    desc: dup\n    cmds: [echo dup]\n" > "$out"
check "Task fails the whole run when a flattened include repeats a task name (why shadows are refused)" "203" "$(cd "$W" && task --list >/dev/null 2>&1; echo $?)"
printf "version: '3'\ntasks:\n  'dc:up':\n    desc: dup\n    cmds: [echo dup]\n" > "$out"
check "...and when a wrapper is named like an included task (dc:up)" "203" "$(cd "$W" && task --list >/dev/null 2>&1; echo $?)"
cp "$T/good.yml" "$out"
# a stale generated file with such a clash must not stop the next generation
printf "version: '3'\ntasks:\n  real:\n    desc: dup\n    cmds: [echo dup]\n" > "$out"
r="$(regen)"
check "a stale generated file that breaks Task does not stop regeneration" "ok" "$(echo "$r" | awk '$1 == "ok1" { print $3 }')"

# Task's variable rule, why a target should take its input as `{{.X | default ...}}`: a static
# `vars:` default of the target wins over a call's vars in Task 3.54.
cat > "$W/Taskfile.static.yml" <<'E'
version: '3'
tasks:
  t:
    vars: { P: fixed }
    cmds: ['echo P={{.P}}']
  c:
    cmds:
      - task: t
        vars: { P: me }
E
check "(recorded) a call's vars do not override a target's static var default in this Task" "P=fixed" "$(cd "$W" && task -t Taskfile.static.yml c --silent 2>&1)"
rm "$W/Taskfile.static.yml"

# ---------------------------------------------------------------- 4. never fatal
check_valid() { # <name>: exit 0 handled by caller; the generated file is a valid Taskfile
  check "$1: the generated file is valid for task --list" "0" "$(cd "$W" && task --list >/dev/null 2>&1; echo $?)"
  check "$1: the generated file is a Taskfile with tasks" "!!map" "$("$yq" '.tasks | tag' "$out")"
}
printf 'aliases: [unclosed\n  : :\n' > "$team"
r="$(regen)"; rc=$?
check "bad YAML: exit 0" "0" "$rc"
contains "bad YAML: reported" "invalid" "$r"
check_valid "bad YAML"
printf 'aliases: { a: real }\nother: 1\n' > "$team"
contains "an unknown top-level key rejects the file" "unknown top-level key" "$(regen)"
printf 'aliases: nope\n' > "$team"
contains "aliases that is not a map" "aliases is not a map" "$(regen)"
rm "$team"
r="$(regen)"; rc=$?
check "no team file: exit 0" "0" "$rc"
contains "no team file: said so" "no team file" "$r"
check_valid "no team file"
printf 'aliases: { a: real }\n' > "$team"
mv "$W/Taskfile.yml" "$W/Taskfile.off"
r="$(regen "$T")"; rc=$?
mv "$W/Taskfile.off" "$W/Taskfile.yml"
check "no root Taskfile: exit 0" "0" "$rc"
contains "no root Taskfile: said so" "cannot read the tasks" "$r"
check_valid "no root Taskfile"
r="$(cd "$W" && TASK_ALIASES_YQ=/nonexistent/yq task-aliases generate 2>&1)"; rc=$?
check "no yq: exit 0" "0" "$rc"
contains "no yq: said so" "yq not found" "$r"
check_valid "no yq"
r="$(cd "$W" && TASK_ALIASES_TASK=/nonexistent/task task-aliases generate 2>&1)"; rc=$?
check "no task binary: exit 0" "0" "$rc"
check_valid "no task binary"
check "a usage error exits 2" "2" "$(task-aliases bogus >/dev/null 2>&1; echo $?)"

# the option's file: from aliases.conf, relative to the root Taskfile's folder; the variable beats it
mkdir -p "$W/conf"
printf 'aliases: { viaconf: real }\n' > "$W/conf/team.yml"
printf 'team=conf/team.yml\n' > "$GO_TASK_SHARE/aliases.conf"
contains "teamAliasesFile (aliases.conf) is read, relative to the root Taskfile" "viaconf" "$(regen "$W/sub")"
printf 'aliases: { viaenv: real }\n' > "$W/conf/env.yml"
contains "GO_TASK_TEAM_ALIASES_FILE beats the option" "viaenv" "$(cd "$W" && GO_TASK_TEAM_ALIASES_FILE="$W/conf/env.yml" task-aliases generate 2>&1)"
rm "$GO_TASK_SHARE/aliases.conf"

# the exit status: strict (a hand run) fails on a bad alias, the default (container start) never does
printf 'aliases: { good: real, bad: nosuch }\n' > "$team"
(cd "$W" && task-aliases generate --strict >/dev/null 2>&1); check "strict: a broken alias exits 1" "1" "$?"
(cd "$W" && task-aliases generate >/dev/null 2>&1); check "start run: a broken alias exits 0" "0" "$?"
printf 'aliases: { Bad Name: real }\n' > "$team"
(cd "$W" && task-aliases generate --strict >/dev/null 2>&1); check "strict: an invalid alias exits 1" "1" "$?"
printf 'aliases: { good: real }\n' > "$team"
(cd "$W" && task-aliases generate --strict >/dev/null 2>&1); check "strict: a clean file exits 0" "0" "$?"
(cd "$W" && task-aliases generate >/dev/null 2>&1); check "start run: a clean file exits 0" "0" "$?"
(cd "$W" && TASK_ALIASES_YQ=/nonexistent/yq task-aliases generate --strict >/dev/null 2>&1); check "strict: no yq exits 1" "1" "$?"

echo
echo "go-task aliases: $pass passed, $fail failed"
[ "$fail" -eq 0 ]
